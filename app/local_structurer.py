# Фразы, по которым видно сопротивление идее терапии.
_THERAPY_RESISTANCE = ("не хочу к психологу", "не хочу к психотерапевту", "не пойду к психологу")
_THERAPY_MENTION = ("психолог", "психотерапевт", "терапи")

_AGE_RE = re.compile(r"(\d{1,2})\s*(?:года|год|лет)", re.IGNORECASE)
_DURATION_RE = re.compile(r"(\d{1,2})\s*(?:год|года|лет)\s+(?:уже\s+)?", re.IGNORECASE)


def _detect_topics(text: str) -> list[str]:
    lowered = text.lower()
    found: list[str] = []
    for topic, data in _TOPICS.items():
        keywords = data["keywords"]  # type: ignore[index]
        if any(keyword in lowered for keyword in keywords):  # type: ignore[union-attr]
            found.append(topic)
    return found


def _human_list(items: list[str]) -> str:
    """Собирает перечисление по-русски: «а, б и в»."""
    if not items:
        return ""
    if len(items) == 1:
        return items[0]
    return f"{', '.join(items[:-1])} и {items[-1]}"


def _facts_line(text: str) -> str:
    """Короткая строка с фактами, которые нужно сохранить без искажений."""
    numbers = extract_numbers(text)
    names = extract_names(text)
    places = extract_places(text)
    parts: list[str] = []
    if names:
        parts.append(f"имена: {_human_list(names)}")
    if places:
        parts.append(f"названия мест: {_human_list(places)}")
    if numbers:
        parts.append(f"числа: {_human_list(numbers)}")
    if not parts:
        return ""
    return "Сохраняю ваши формулировки — " + "; ".join(parts) + "."


def _truncate(text: str, limit: int) -> str:
    """Обрезает текст по границе слова, не разрывая его посередине."""
    if len(text) <= limit:
        return text

    cut = text[:limit]
    space_index = cut.rfind(" ")
    if space_index > limit * 0.6:
        cut = cut[:space_index]
    return cut.rstrip(" ,;:—-") + "…"


def _topic_list(labels: list[str]) -> str:
    """Перечисление тем через точку с запятой — названия тем сами содержат «и»."""
    return "; ".join(labels)


def _overview(text: str, topics: list[str]) -> str:
    sentences = split_sentences(text)
    first = sentences[0] if sentences else text.strip()
    first = _truncate(first, 240)

    topic_labels = [_TOPICS[topic]["label"] for topic in topics][:3]  # type: ignore[index]

    if topic_labels:
        intro = (
            "Вы описали ситуацию, в которой заметны темы: "
            f"{_topic_list(topic_labels)}."
        )
    else:
        intro = "Вы описали ситуацию, которую хочется разобрать спокойно и по частям."

    age_match = _AGE_RE.search(text)
    if age_match:
        intro += f" В тексте указан возраст — {age_match.group(0).strip()}."

    return f"{intro} Вот как это выглядит со стороны, если собрать всё воедино: {first}"


def _hypotheses(text: str, topics: list[str]) -> list[str]:
    lowered = text.lower()
    hypotheses: list[str] = []

    for topic in topics:
        for hypothesis in _TOPICS[topic]["hypotheses"]:  # type: ignore[index]
            if hypothesis not in hypotheses:
                hypotheses.append(hypothesis)

    if any(phrase in lowered for phrase in _THERAPY_RESISTANCE):
        hypotheses.append(
            "Вероятно, за нежеланием идти к специалисту может стоять не отказ "
            "от помощи, а осторожность или сомнение, что это сработает."
        )
    elif any(word in lowered for word in _THERAPY_MENTION):
        hypotheses.append(
            "Может быть, мысль о разговоре со специалистом уже появилась, "
            "и сейчас важно понять, что именно останавливает."
        )

    if not hypotheses:
        hypotheses = [
            "Возможно, в этой ситуации смешалось несколько разных переживаний, "
            "и их стоит разделить, чтобы стало понятнее.",
            "Кажется, что сейчас вам не хватает опоры или человека, с которым "
            "можно спокойно проговорить всё это вслух.",
        ]

    return hypotheses[:4]


def _discuss(text: str, topics: list[str]) -> str:
    parts = [_TOPICS[topic]["discuss"] for topic in topics][:3]  # type: ignore[index]
    if not parts:
        parts = [
            "то, что происходит сейчас",
            "ваши чувства в этой ситуации",
            "чего вам не хватает",
        ]

    base = "С психологом можно обсудить: " + "; ".join(parts) + "."

    age_match = _AGE_RE.search(text)
    names = extract_names(text)

    details: list[str] = []
    if names:
        details.append(f"людей, которых вы называли ({_human_list(names)}),")
    if age_match:
        details.append(
            f"ваш возраст и то, как он связан с происходящим ({age_match.group(0).strip()}),"
        )

    if details:
        base += " Отдельно стоит упомянуть: " + "; ".join(
            detail.rstrip(",") for detail in details
        ) + "."
    return base


def structure_locally(text: str) -> dict:
    """Возвращает результат в той же структуре, что и LLM."""
    topics = _detect_topics(text)

    overview = _overview(text, topics)
    facts_line = _facts_line(text)
    if facts_line:
        overview = f"{overview}\n\n{facts_line}"

    return {
        "sections": [
            {"title": "Что происходит", "body": overview},
            {
                "title": "Что, возможно, за этим стоит",
                "bullets": _hypotheses(text, topics),
            },
            {"title": "О чём поговорить с психологом", "body": _discuss(text, topics)},
        ],
        "hasRedFlags": False,
        "source": "local",
    }
