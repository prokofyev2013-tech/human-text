"""Детекция «красных флагов» в тексте пользователя (ТЗ п. 5.3).

Проверка работает по ключевым формулировкам и не претендует на роль
диагностического инструмента: задача — не пропустить кризисные темы
и показать бережное предупреждение.
"""

from __future__ import annotations

import re

# Каждая группа — отдельная тема. Регулярные выражения написаны так, чтобы
# покрывать типичные разговорные формулировки, а не только «книжные».
_PATTERNS: dict[str, tuple[str, ...]] = {
    "suicide": (
        r"хочу\s+умереть",
        r"хочу\s+сдохнуть",
        r"не\s+хочу\s+жить",
        r"не\s+вижу\s+смысла\s+жить",
        r"нет\s+смысла\s+жить",
        r"лучше\s+бы\s+меня\s+не\s+было",
        r"лучше\s+бы\s+я\s+умер",
        r"покончить\s+с\s+собой",
        r"свести\s+счеты\s+с\s+жизнью",
        r"суицид",
    ),
    "self_harm": (
        r"режу\s+себя",
        r"режу\s+руки",
        r"причинить\s+себе\s+боль",
        r"причиняю\s+себе\s+боль",
        r"наношу\s+себе\s+(по)?вреждени",
        r"самоповреждени",
        r"себе\s+вред",
    ),
    "acute_crisis": (
        r"меня\s+преследуют",
        r"я\s+в\s+опасности",
        r"не\s+могу\s+дышать\s+от\s+страха",
        r"паническ(ая|ую)\s+атака",
        r"накрывает\s+паник",
        r"схожу\s+с\s+ума",
    ),
    "violence": (
        r"он\s+меня\s+бьет",
        r"она\s+меня\s+бьет",
        r"меня\s+бьют",
        r"меня\s+избива",
        r"меня\s+заставляют",
        r"меня\s+насилуют",
        r"насилие\s+в\s+семье",
        r"угрожает\s+убить",
        r"душит\s+меня",
    ),
}

_COMPILED: dict[str, re.Pattern[str]] = {
    topic: re.compile("|".join(f"(?:{p})" for p in patterns), re.IGNORECASE)
    for topic, patterns in _PATTERNS.items()
}


def detect_red_flags(text: str) -> tuple[bool, list[str]]:
    """Возвращает (есть_ли_флаги, список_затронутых_тем)."""
    if not text:
        return False, []

    found = [topic for topic, pattern in _COMPILED.items() if pattern.search(text)]
    return bool(found), found
